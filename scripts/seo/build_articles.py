# These pages carry NO release version, anywhere — not in the prose, not in
# the footer brand line. That is deliberate.
#
# A version stamp is a claim that goes stale on its own. This footer was
# hardcoded to `V1.0.0-RC.15`, copied from a page written when that was
# current, and it sat there for eight releases until
# `.github/scripts/landing-constants-guard.sh` failed the build. Deriving it
# from the newest tag fixes the drift but keeps a claim these pages do not
# need to make: an answer page tells a reader to install the latest XERJ, so
# naming a release only invites the question of whether the page still applies
# to it.
#
# The guard is satisfied by absence, not by agreement. It matches
# `XERJ.AI[^<]*V1.0.0-RC.?[0-9]+` and flags only stamps that DISAGREE with the
# newest tag, so a footer without one is never examined. Do not "fix" this by
# adding a version back — that re-creates the drift the guard exists to catch,
# and it would be the only version string on pages whose whole point is that
# they do not depend on one.
