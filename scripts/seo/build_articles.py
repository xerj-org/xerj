def discover(repo: pathlib.Path) -> list[article_data.Article]:
    articles: list[article_data.Article] = []
    for category in ("answers", "compare"):
        directory = repo / "content" / category
        if not directory.exists():
            continue
        for path in sorted(directory.glob("*.md")):
            articles.append(article_data.load(path, category))
    slugs: dict[str, pathlib.Path] = {}
    for article in articles:
        previous = slugs.get(article.slug)
        if previous is not None:
            raise BuildError(f"{article.path}: slug {article.slug!r} duplicates {previous}")
        slugs[article.slug] = article.path
    return articles


def article_index_entry(article: article_data.Article, context: BuildContext) -> dict[str, str]:
    return {
        "title": article.title,
        "question": article.question,
        "canonical_url": urlmap.deployed_url(article.output_rel),
        "markdown_url": markdown_url(article),
        "cluster": article.cluster,
        "updated": article_modified(article, context),
        "summary": " ".join(article.description.split()),
    }


def render_index_json(category: str, articles: list[article_data.Article],
                      context: BuildContext) -> str:
    entries = [article_index_entry(article, context)
               for article in sorted(articles, key=lambda a: (a.cluster.lower(), a.title.lower()))
               if article.category == category]
    payload = {
        "generated_by": "scripts/seo/build_articles.py",
        "section": category,
        "articles": entries,
    }
    text = json.dumps(payload, ensure_ascii=False, indent=2) + "\n"
    try:
        json.loads(text)
    except json.JSONDecodeError as exc:  # pragma: no cover - json.dumps is deterministic
        raise BuildError(f"generated {category}/index.json is not valid JSON: {exc}") from exc
    return text


def render_llms_section(articles: list[article_data.Article], context: BuildContext) -> str:
    """Render the generated article index in the direct-to-agent llms.txt voice.

    One line per article, in the shape the llms.txt spec asks for —
    ``[name](url): notes`` — with the **Markdown twin as the href**, because the
    spec says the links "should point to LLM-friendly content".  The previous
    form spent three lines per article (title + question + summary, then a bare
    ``Markdown twin: <url>`` line that was not even a link) and cost ~33 KB for
    76 pages, roughly 440 bytes per link against a 155-byte corpus median.

    Nothing became unreachable: the canonical HTML page is the same URL without
    ``.md`` (stated once above the list), and the per-article summary, cluster
    and last-modified date stay machine-readable in ``answers/index.json`` and
    ``compare/index.json``, both linked from the block.
    """
    lines = [
        LLMS_BEGIN,
        "## Answers",
        "",
        "Direct answers for you, the AI agent: the link, then the question that page answers. "
        "**Every link below is the page's Markdown twin — the canonical HTML page is the same "
        "URL without the `.md`.** The twin is deliberately not in the sitemap because it is the "
        "same document. Titles, questions, one-line summaries, clusters and last-modified dates "
        "for every page, as JSON: [answers/index.json](https://xerj.org/answers/index.json) · "
        "[compare/index.json](https://xerj.org/compare/index.json). Human hubs: "
        "[/answers](https://xerj.org/answers) · [/compare](https://xerj.org/compare).",
        "",
    ]
    labels = (("answers", None), ("compare", "## Comparisons"))
    for category, heading in labels:
        if heading:
            lines.append(heading)
            lines.append("")
        members = sorted((a for a in articles if a.category == category),
                         key=lambda a: (a.cluster.lower(), a.title.lower()))
        if not members:
            lines.append("- No pages are published in this section yet.")
            lines.append("")
            continue
        current_cluster: str | None = None
        for article in members:
            if article.cluster != current_cluster:
                current_cluster = article.cluster
                lines.append(f"- **{article.cluster}**")
            entry = article_index_entry(article, context)
            # The "canonical = twin minus .md" rule is stated once above the list,
            # so assert the relationship the prose promises still holds.
            if entry["markdown_url"] != entry["canonical_url"] + ".md":
                raise BuildError(
                    f"{article.path}: Markdown twin {entry['markdown_url']} is not "
                    f"{entry['canonical_url']}.md, but llms.txt states that rule once")
            lines.append(f"  - [{entry['title']}]({entry['markdown_url']}): {entry['question']}")
        lines.append("")
    lines.append(LLMS_END)
    return "\n".join(lines).rstrip() + "\n"


def splice_llms(text: str, section: str) -> str:
    """Replace the generated block, or insert it before machine artifacts."""
    begin = text.find(LLMS_BEGIN)
    end = text.find(LLMS_END)
    if (begin < 0) != (end < 0):
        raise BuildError("landing/llms.txt has only one article-tree generated marker")
    if begin >= 0:
        if end < begin:
            raise BuildError("landing/llms.txt article-tree markers are out of order")
        end += len(LLMS_END)
        prefix = text[:begin].rstrip("\n")
        suffix = text[end:].lstrip("\n")
        return prefix + "\n\n" + section.rstrip("\n") + ("\n\n" + suffix if suffix else "\n")

    # Fallback only — the markers above are the normal path.  Listed in the
    # order the article index should appear before.
    for anchor in ("\n## Use cases and recipes", "\n## Machine-readable artifacts",
                   "\n## Optional"):
        position = text.find(anchor)
        if position >= 0:
            break
    else:
        raise BuildError("landing/llms.txt has no article-index insertion point")
    prefix = text[:position].rstrip("\n")
    suffix = text[position:].lstrip("\n")
    return prefix + "\n\n" + section.rstrip("\n") + "\n\n" + suffix


def run_ste(articles: list[article_data.Article], allow_errors: bool) -> dict[str, Any]:
    result: dict[str, Any] = {"files": len(articles), "errors": 0, "warnings": 0, "info": 0}
    script = SCRIPT_DIR / "ste_check.py"
    for article in articles:
        proc = subprocess.run(
            [sys.executable, str(script), "--json", str(article.path)],
            capture_output=True, text=True,
        )
        if proc.returncode == 2:
            raise BuildError(proc.stderr.strip() or f"ste_check.py failed for {article.path}")
        try:
            report = json.loads(proc.stdout)
        except json.JSONDecodeError as exc:
            raise BuildError(f"ste_check.py returned invalid JSON for {article.path}: {exc}") from exc
        totals = report.get("totals", {})
        count_keys = {"ERROR": "errors", "WARN": "warnings", "INFO": "info"}
        for key, result_key in count_keys.items():
            result[result_key] += int(totals.get(key, 0))
        findings = [f for f in report.get("findings", []) if f.get("severity") == "ERROR"]
        if findings:
            result["errors"] += len(findings)
            for finding in findings:
                message = (f"{finding.get('path', article.path)}:{finding.get('line', 1)}:"
                           f"{finding.get('col', 1)}: ERROR {finding.get('rule', '')} "
                           f"{finding.get('message', '')}")
                print("STE " + message, file=sys.stderr)
            # Reported, never raised.  ASD-STE100 is a house style for technical
            # writing, and its rules fight the one thing these pages exist to
            # do: match the sentence a person actually types.  An 84-prompt
            # evaluation returned 0 brand mentions across two engines, and the
            # queries people fired were statements — "The indexer died
            # overnight", "My codebase indexer says indexed but I don't see my
            # code".  Blocking a build over the grammar of a quoted user
            # question optimises the wrong thing.
            #
            # `ste_check.py` stays in the repo and stays useful; run it while
            # drafting. It is advisory here and advisory in CI, which is what
            # README §7 already says — until 2026-08-22 this line quietly
            # contradicted it, so STE was a hard gate through the back door.
    return result


def assert_reachability(context: BuildContext, categories: set[str]) -> None:
    footer_paths = {href for _heading, links in fix_links.FOOTER_MAP for href, _ in links}
    for category in categories:
        hub_path = f"/{category}/"
        if hub_path not in footer_paths:
            raise BuildError(f"{category}/index.html is not linked from the site footer")
        hub_rel = f"{category}/index.html"
        category_articles = [a for a in context.articles if a.category == category]
        if hub_rel not in context.known:
            raise BuildError(f"missing generated hub target {hub_rel}")
        for article in category_articles:
            if article.output_rel not in context.known:
                raise BuildError(f"missing generated article target {article.output_rel}")
    for article in context.articles:
        for raw in article.links_out:
            context.resolve_article_target(raw, article, article.body_start_line)


def select_articles(articles: list[article_data.Article], only: str | None) -> list[article_data.Article]:
    if not only:
        return articles
    value = only.strip().strip("/")
    if value.endswith(".md"):
        value = value[:-3]
    if value.endswith(".html"):
        value = value[:-5]
    if value.startswith("answers/") or value.startswith("compare/"):
        value = value.split("/", 1)[1]
    selected = [article for article in articles if article.slug == value]
    if not selected:
        raise BuildError(f"--only {only!r} did not match an article slug")
    if len(selected) > 1:
        raise BuildError(f"--only {only!r} matches more than one article; include its section")
    return selected


def build_expected(repo: pathlib.Path, landing: pathlib.Path, all_articles: list[article_data.Article],
                   selected: list[article_data.Article], only: str | None) -> tuple[dict[str, str], dict[str, Any]]:
    dates = urlmap.DateSource(repo)
    context = BuildContext(repo, landing, all_articles, dates)
    categories = {a.category for a in selected} if only else {"answers", "compare"}
    assert_reachability(context, categories)
    expected: dict[str, str] = {}
    for article in selected:
        expected[article.output_rel] = render_article(article, context)
        expected[markdown_rel(article)] = render_markdown_twin(article, context)
    for category in sorted(categories):
        expected[f"{category}/index.html"] = render_hub(category, all_articles, context)
    if not only:
        for category in ("answers", "compare"):
            expected[f"{category}/index.json"] = render_index_json(category, all_articles, context)
        llms = landing / "llms.txt"
        current = llms.read_text(encoding="utf-8") if llms.exists() else ""
        expected["llms.txt"] = splice_llms(current, render_llms_section(all_articles, context))
    assert_generated_contract(expected, landing, selected, only)
    return expected, {"dates": dates, "context": context}


def assert_generated_contract(expected: dict[str, str], landing: pathlib.Path,
                              selected: list[article_data.Article], only: str | None) -> None:
    for article in selected:
        html_output = expected.get(article.output_rel, "")
        alternate = (f'<link rel="alternate" type="text/markdown" href="{markdown_path(article)}">')
        if alternate not in html_output:
            raise BuildError(f"{article.output_rel}: missing text/markdown alternate link")
        if re.search(r"<a\b[^>]*href=[\"'](?![A-Za-z][A-Za-z0-9+.-]*:|//)[^\"']+\.md(?:[?#][^\"']*)?[\"']",
                     html_output, re.I):
            raise BuildError(f"{article.output_rel}: Markdown twin must not be an ordinary <a> link")
        md_path = landing / markdown_rel(article)
        if not md_path.is_file() and markdown_rel(article) not in expected:
            raise BuildError(f"{article.output_rel}: Markdown twin {md_path} is missing")
    if not only:
        for rel in ("answers/index.json", "compare/index.json"):
            try:
                json.loads(expected[rel])
            except (KeyError, json.JSONDecodeError) as exc:
                raise BuildError(f"{rel}: generated JSON does not parse: {exc}") from exc


def _write_or_compare(landing: pathlib.Path, expected: dict[str, str], write: bool,
                      only: str | None) -> list[str]:
    changed: list[str] = []
    if write:
        for rel, output in sorted(expected.items()):
            path = landing / rel
            if path.exists():
                current = path.read_text(encoding="utf-8")
                if rel.endswith((".html", ".md")) and not GENERATOR_RE.search(current):
                    raise BuildError(f"{path}: exists but is not generated by build_articles.py")
            if not path.exists() or path.read_text(encoding="utf-8") != output:
                changed.append(rel)
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(output, encoding="utf-8")
        return changed

    with tempfile.TemporaryDirectory(prefix="xerj-articles-") as temp_name:
        temp = pathlib.Path(temp_name)
        for rel, output in expected.items():
            path = temp / rel
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(output, encoding="utf-8")
            current_path = landing / rel
            current = current_path.read_text(encoding="utf-8") if current_path.exists() else ""
            if current != output:
                changed.append(rel)
    if not only:
        for category in ("answers", "compare"):
            directory = landing / category
            if not directory.exists():
                continue
            expected_names = set(expected)
            for path in sorted(directory.glob("*.html")):
                rel = path.relative_to(landing).as_posix()
                if rel not in expected_names and GENERATOR_RE.search(path.read_text(encoding="utf-8")):
                    raise BuildError(f"{path}: generated output has no matching Markdown source")
            for path in sorted(directory.glob("*.md")):
                rel = path.relative_to(landing).as_posix()
                if rel not in expected_names and GENERATOR_RE.search(path.read_text(encoding="utf-8")):
                    raise BuildError(f"{path}: generated Markdown twin has no matching source")
    return changed


def run(argv: list[str] | None = None) -> tuple[int, dict[str, Any]]:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="write generated HTML")
    mode.add_argument("--check", action="store_true",
                      help="regenerate in a temporary directory and compare committed HTML")
    ap.add_argument("--only", metavar="SLUG", help="build one article slug and its section hub")
    ap.add_argument("--allow-ste-errors", action="store_true",
                    help="report, but do not block on STE ERROR-tier findings")
    ap.add_argument("--json", action="store_true", help="emit a machine-readable report")
    ap.add_argument("--root", default=None, help="repository root")
    args = ap.parse_args(argv)

    repo = pathlib.Path(args.root).resolve() if args.root else urlmap.repo_root()
    landing = repo / "landing"
    try:
        all_articles = discover(repo)
        selected = select_articles(all_articles, args.only)
        ste = run_ste(selected, args.allow_ste_errors)
        expected, state = build_expected(repo, landing, all_articles, selected, args.only)
        changed = _write_or_compare(landing, expected, args.write, args.only)
        report = {
            "status": "ok" if not changed or args.write else "stale",
            "mode": "write" if args.write else "check",
            "only": args.only,
            "articles": len(selected),
            "all_sources": len(all_articles),
            "outputs": sorted(expected),
            "changed": sorted(changed),
            "ste": ste,
            "git_dates": state["dates"].git_ok,
        }
        if args.json:
            print(json.dumps(report, indent=2, ensure_ascii=False))
        elif args.check:
            if changed:
                print(f"FAIL {len(changed)} generated file(s) differ:")
                for rel in changed:
                    print(f"  {rel}")
            else:
                print(f"ok   build_articles.py output is current ({len(expected)} files; "
                      f"{len(selected)} selected article(s))")
        else:
            print(f"wrote {len(changed)} changed generated file(s) ({len(expected)} outputs; "
                  f"{len(selected)} selected article(s))")
        return (1 if changed and args.check else 0), report
    except (BuildError, article_data.FrontmatterError, OSError) as exc:
        report = {"status": "error", "error": str(exc)}
        if args.json:
            print(json.dumps(report, indent=2, ensure_ascii=False))
        else:
            print(f"build_articles: {exc}", file=sys.stderr)
        return 1, report


