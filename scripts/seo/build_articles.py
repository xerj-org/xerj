#!/usr/bin/env python3
"""Build the Markdown article sections of xerj.org.

The generator has no runtime dependencies beyond Python's standard library.
Sources live under ``content/answers`` and ``content/compare``.  The output is
deliberately small, deterministic HTML that uses the site's existing nav,
docs-shell, CSS classes, head emitter and footer.
"""

