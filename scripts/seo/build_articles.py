GENERATOR_PREFIX = "<!-- generated by build_articles.py — edit content/"
GENERATOR_RE = re.compile(
    r"<!-- generated by build_articles\.py — edit content/(answers|compare)/"
    r"(?:[a-z0-9-]+|\*)\.md instead -->"
)
LLMS_BEGIN = "<!-- BEGIN GENERATED ARTICLE TREE: build_articles.py -->"
LLMS_END = "<!-- END GENERATED ARTICLE TREE: build_articles.py -->"
HTML_TAG_RE = re.compile(r"<!--|<![A-Za-z]|</?[A-Za-z][^>]*>")
FENCE_RE = re.compile(r"^ {0,3}(`{3,}|~{3,})(.*)$")
HEADING_RE = re.compile(r"^ {0,3}(#{1,6})\s+(.+?)\s*$")
UL_RE = re.compile(r"^ {0,3}([-+*])\s+(.+?)\s*$")
OL_RE = re.compile(r"^ {0,3}(\d+)[.)]\s+(.+?)\s*$")
LANG_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9+_.-]*$")
TLDR_RE = re.compile(r"^\s*\*\*TL[;:]?DR\*\*\s*[—–:.-]?\s*", re.I)


class BuildError(ValueError):
    """A user-actionable build error."""


class LinkTarget:
    __slots__ = ("rel", "href", "label")

    def __init__(self, rel: str, href: str, label: str):
        self.rel = rel
        self.href = href
        self.label = label


def esc_text(value: str) -> str:
    return html.escape(value, quote=False)


def esc_attr(value: str) -> str:
    return html.escape(value, quote=True)


def line_error(article: article_data.Article, line: int, message: str) -> BuildError:
    return BuildError(f"{article.path}:{line}: {message}")


class BuildContext:
    def __init__(self, repo: pathlib.Path, landing: pathlib.Path,
                 articles: list[article_data.Article], dates: urlmap.DateSource):
        self.repo = repo
        self.landing = landing
        self.dates = dates
        self.articles = articles
        self.by_rel = {a.output_rel: a for a in articles}
        self.by_slug: dict[str, list[article_data.Article]] = collections.defaultdict(list)
        for article in articles:
            self.by_slug[article.slug].append(article)
        self.existing = set(urlmap.iter_pages(landing))
        self.known = self.existing | set(self.by_rel) | {
            "answers/index.html", "compare/index.html",
        }

    def _normalise_path(self, raw: str, category: str) -> tuple[str, str, str]:
        value = raw.strip()
        if not value:
            raise BuildError("empty internal link target")
        parsed = urllib.parse.urlsplit(value)
        if parsed.scheme or value.startswith("//"):
            if parsed.scheme not in ("http", "https") or parsed.netloc not in (
                    "xerj.org", "www.xerj.org"):
                raise BuildError(f"internal article link must stay on xerj.org: {raw!r}")
            path = parsed.path or "/"
        else:
            path = parsed.path
            if not path.startswith("/"):
                if path.startswith(("answers/", "compare/", "docs/", "use-cases/",
                                    "case-studies/", "industries/")):
                    path = "/" + path
                else:
                    # A bare value is an article slug in the current section.
                    path = f"/{category}/{path}"
        if "\\" in path:
            raise BuildError(f"backslashes are not valid in internal link target {raw!r}")
        path = posixpath.normpath(path)
        if not path.startswith("/"):
            path = "/" + path
        if path == "/.":
            path = "/"
        return path, parsed.query, parsed.fragment

    def resolve(self, raw: str, category: str, article: article_data.Article | None = None,
                line: int | None = None) -> LinkTarget:
        try:
            path, query, fragment = self._normalise_path(raw, category)
        except BuildError as exc:
            if article is not None and line is not None:
                raise line_error(article, line, str(exc)) from exc
            raise
        rel = urlmap.rel_for_path(path)
        if rel is None or rel not in self.known or not (
                (self.landing / rel).is_file() or rel in self.by_rel):
            message = f"dangling internal target {raw!r} (resolved as {path})"
            if article is not None and line is not None:
                raise line_error(article, line, message)
            raise BuildError(message)
        target = self.by_rel.get(rel)
        if target is not None:
            label = target.h1
        else:
            try:
                label = str(pagedata.entry(rel).get("label", rel))
            except KeyError:
                label = rel
        href = urlmap.deployed_path(rel)
        if query:
            href += "?" + query
        if fragment:
            href += "#" + fragment
        return LinkTarget(rel, href, label)

    def resolve_article_target(self, raw: str, article: article_data.Article,
                               line: int | None = None) -> LinkTarget:
        """Resolve a links_out item, including a bare slug."""
        value = raw.strip()
        parsed = urllib.parse.urlsplit(value)
        bare = parsed.path.strip("/")
        if not parsed.scheme and not value.startswith("/") and "/" not in bare:
            matches = self.by_slug.get(bare, [])
            if len(matches) == 1:
                return self.resolve(matches[0].output_rel, article.category, article, line)
            if len(matches) > 1:
                raise line_error(article, line or 1,
                                 f"ambiguous article slug {raw!r}; use /answers/... or /compare/...")
        return self.resolve(value, article.category, article, line)

    def markdown_href(self, raw: str, article: article_data.Article,
                      line: int) -> str:
        parsed = urllib.parse.urlsplit(raw.strip())
        if parsed.scheme in ("http", "https") and parsed.netloc:
            return raw.strip()
        if parsed.scheme or raw.strip().startswith("//"):
            raise line_error(article, line, f"unsupported Markdown link URL {raw!r}")
        return self.resolve(raw, article.category, article, line).href


def _check_raw_html(lines: list[str], article: article_data.Article) -> None:
    in_fence = False
    marker = ""
    for offset, raw in enumerate(lines):
        line_no = article.body_start_line + offset
        fence = FENCE_RE.match(raw)
        if fence:
            token = fence.group(1)
            if not in_fence:
                in_fence = True
                marker = token[0]
            elif token[0] == marker:
                in_fence = False
            continue
        if in_fence:
            continue
        masked = re.sub(r"`[^`]*`", "", raw)
        if HTML_TAG_RE.search(masked):
            raise line_error(article, line_no, "raw HTML is not allowed in Markdown")
    if in_fence:
        raise line_error(article, article.body_start_line + len(lines),
                         "fenced code block has no closing fence")


def _split_table_row(raw: str) -> list[str]:
    text = raw.strip()
    if text.startswith("|"):
        text = text[1:]
    if text.endswith("|") and not text.endswith("\\|"):
        text = text[:-1]
    cells: list[str] = []
    current: list[str] = []
    escaped = False
    for ch in text:
        if escaped:
            current.append(ch)
            escaped = False
        elif ch == "\\":
            escaped = True
        elif ch == "|":
            cells.append("".join(current).strip())
            current = []
        else:
            current.append(ch)
    if escaped:
        current.append("\\")
    cells.append("".join(current).strip())
    return cells


def _is_table_separator(raw: str) -> bool:
    if "|" not in raw:
        return False
    cells = _split_table_row(raw)
    return bool(cells) and all(re.fullmatch(r":?-{3,}:?", cell) for cell in cells)


def _is_word_char(ch: str) -> bool:
    """Return True for characters that make ``_`` intraword, not emphasis."""
    return ch.isalnum() or ch == "_"


def _inline(text: str, article: article_data.Article, line: int,
            href_resolver: Callable[[str, article_data.Article, int], str]) -> str:
    """Render the safe inline subset with escaping at the text boundary."""
    out: list[str] = []
    i = 0
    n = len(text)
    while i < n:
        if text.startswith("![", i):
            raise line_error(article, line, "images are not supported in article Markdown")
        if text[i] == "`":
            end = text.find("`", i + 1)
            if end < 0:
                raise line_error(article, line, "inline code span has no closing backtick")
            out.append(f'<code class="inline">{esc_text(text[i + 1:end])}</code>')
            i = end + 1
            continue
        marker = None
        width = 0
        if text.startswith("**", i) or text.startswith("__", i):
            marker, width = text[i:i + 2], 2
        elif text[i] in "*_":
            marker, width = text[i], 1
        if marker is not None and marker[0] == "_" and i > 0 and _is_word_char(text[i - 1]):
            # CommonMark forbids intraword ``_`` emphasis so that bare
            # identifiers such as ``ignored_files`` stay literal text.
            marker = None
        if marker is not None:
            end = text.find(marker, i + width)
            if marker[0] == "_":
                # A closing ``_`` may not be followed by a word character
                # either, for the same reason.
                while end >= 0 and end + width < n and _is_word_char(text[end + width]):
                    end = text.find(marker, end + width)
            if end > i + width and not text[i + width].isspace():
                inner = _inline(text[i + width:end], article, line, href_resolver)
                tag = "strong" if width == 2 else "em"
                out.append(f"<{tag}>{inner}</{tag}>")
                i = end + width
                continue
        if text[i] == "[":
            close = text.find("]", i + 1)
            if close > i + 1 and close + 1 < n and text[close + 1] == "(":
                end = text.find(")", close + 2)
                if end < 0:
                    raise line_error(article, line, "Markdown link has no closing parenthesis")
                label = text[i + 1:close]
                destination = text[close + 2:end].strip()
                if not destination or any(ch.isspace() for ch in destination):
                    raise line_error(article, line, "Markdown links need a single URL without spaces")
                href = href_resolver(destination, article, line)
                out.append(f'<a href="{esc_attr(href)}">'
                           f"{_inline(label, article, line, href_resolver)}</a>")
                i = end + 1
                continue
        start = i
        while i < n and text[i] not in "`[*_":
            i += 1
        if start == i:
            out.append(esc_text(text[i]))
            i += 1
        else:
            out.append(esc_text(text[start:i]))
    return "".join(out)


def _block_start(lines: list[str], i: int) -> bool:
    raw = lines[i]
    return bool(FENCE_RE.match(raw) or HEADING_RE.match(raw) or UL_RE.match(raw)
                or OL_RE.match(raw) or raw.lstrip().startswith(">"))


def render_markdown_blocks(article: article_data.Article, context: BuildContext) -> list[str]:
    lines = article.body.splitlines()
    _check_raw_html(lines, article)
    first = next((line for line in lines if line.strip()), "")
    if not TLDR_RE.match(first):
        raise line_error(article, article.body_start_line,
                         "the first body block must be the TL;DR paragraph")

    rendered: list[str] = []
    i = 0
    previous_heading = 1
    while i < len(lines):
        raw = lines[i]
        line_no = article.body_start_line + i
        if not raw.strip():
            i += 1
            continue

        fence = FENCE_RE.match(raw)
        if fence:
            marker = fence.group(1)[0]
            info = fence.group(2).strip()
            if not info or not LANG_RE.fullmatch(info):
                raise line_error(article, line_no,
                                 "fenced code blocks need a simple language name")
            i += 1
            code: list[str] = []
            closed = False
            while i < len(lines):
                close = FENCE_RE.match(lines[i])
                if close and close.group(1)[0] == marker and not close.group(2).strip():
                    closed = True
                    i += 1
                    break
                code.append(lines[i])
                i += 1
            if not closed:
                raise line_error(article, line_no, "fenced code block has no closing fence")
            body = esc_text("\n".join(code))
            if code:
                body += "\n"
            rendered.append(f'  <pre class="code"><code class="language-{info}">'
                            f"{body}</code></pre>")
            continue

        heading = HEADING_RE.match(raw)
        if heading:
            level = len(heading.group(1))
            text = heading.group(2).rstrip("#").rstrip()
            if level == 1:
                raise line_error(article, line_no,
                                 "Markdown body must not contain an H1; use frontmatter h1")
            if level not in (2, 3):
                raise line_error(article, line_no,
                                 "only ATX h2 and h3 headings are supported")
            if level > previous_heading + 1:
                raise line_error(article, line_no,
                                 f"heading level jumps from h{previous_heading} to h{level}")
            if level == 2 and text.strip().lower() == "faq":
                raise line_error(article, line_no,
                                 "FAQ is generated from frontmatter; remove the body FAQ heading")
            rendered.append(f"  <h{level}>"
                            f"{_inline(text, article, line_no, context.markdown_href)}"
                            f"</h{level}>")
            previous_heading = level
            i += 1
            continue

        if (i + 1 < len(lines) and "|" in raw
                and _is_table_separator(lines[i + 1])):
            header = _split_table_row(raw)
            separator = _split_table_row(lines[i + 1])
            if len(header) != len(separator):
                raise line_error(article, line_no, "table header and separator widths differ")
            i += 2
            rows: list[list[str]] = []
            while i < len(lines) and lines[i].strip() and "|" in lines[i]:
                row = _split_table_row(lines[i])
                if len(row) != len(header):
                    raise line_error(article, article.body_start_line + i,
                                     "table row width differs from the header")
                rows.append(row)
                i += 1
            rendered.append("  <table>")
            rendered.append("    <thead><tr>" + "".join(
                f"<th>{_inline(cell, article, line_no, context.markdown_href)}</th>"
                for cell in header) + "</tr></thead>")
            if rows:
                rendered.append("    <tbody>")
                for row_index, row in enumerate(rows):
                    row_line = line_no + 2 + row_index
                    rendered.append("      <tr>" + "".join(
                        f"<td>{_inline(cell, article, row_line, context.markdown_href)}</td>"
                        for cell in row) + "</tr>")
                rendered.append("    </tbody>")
            rendered.append("  </table>")
            continue

        unordered = UL_RE.match(raw)
        ordered = OL_RE.match(raw)
        if unordered or ordered:
            ordered_mode = ordered is not None
            items: list[tuple[int, str]] = []
            while i < len(lines):
                match = OL_RE.match(lines[i]) if ordered_mode else UL_RE.match(lines[i])
                if not match:
                    break
                items.append((article.body_start_line + i, match.group(2)))
                i += 1
            tag = "ol" if ordered_mode else "ul"
            rendered.append(f"  <{tag}>")
            for item_line, item in items:
                rendered.append(f"    <li>{_inline(item, article, item_line, context.markdown_href)}</li>")
            rendered.append(f"  </{tag}>")
            continue

        if raw.lstrip().startswith(">"):
            quote_lines: list[tuple[int, str]] = []
            while i < len(lines) and lines[i].lstrip().startswith(">"):
                quote_lines.append((article.body_start_line + i,
                                    re.sub(r"^ {0,3}>\s?", "", lines[i])))
                i += 1
            text = " ".join(value for _, value in quote_lines)
            rendered.append("  <blockquote><p>"
                            + _inline(text, article, quote_lines[0][0], context.markdown_href)
                            + "</p></blockquote>")
            continue

        paragraph: list[tuple[int, str]] = []
        while i < len(lines) and lines[i].strip() and not _block_start(lines, i):
            paragraph.append((article.body_start_line + i, lines[i].strip()))
            i += 1
        if not paragraph:
            raise line_error(article, line_no, "unsupported Markdown syntax")
        text = " ".join(value for _, value in paragraph)
        rendered.append("  <p>" + _inline(text, article, paragraph[0][0],
                                               context.markdown_href) + "</p>")
    return rendered


def render_markdown(article: article_data.Article, context: BuildContext) -> str:
    return "\n".join(render_markdown_blocks(article, context))


EVIDENCE_LINE_RE = re.compile(r"^(.*):(\d+)$")


def _evidence_repo_path(source: str) -> str:
    """Return the filesystem portion of a repo evidence source."""
    match = EVIDENCE_LINE_RE.fullmatch(source)
    return match.group(1) if match else source


def _metadata_link(source: str, article: article_data.Article,
                   context: BuildContext) -> str | None:
    """Resolve an evidence source, or return ``None`` for repo provenance.

    Evidence sources are not all site links.  A repo-relative source is
    validated against the repository and deliberately has no href so callers
    render it as provenance text rather than an ordinary document link.
    """
    value = source.strip()
    repo_path = _evidence_repo_path(value)
    parsed = urllib.parse.urlsplit(value)
    if parsed.scheme in ("http", "https") and parsed.netloc:
        return value
    if parsed.scheme or value.startswith("//"):
        # urlsplit treats ``ROADMAP.md:80`` as a URI with scheme
        # ``ROADMAP.md``.  Once the trailing line number is removed, a path
        # with no scheme is still a valid repo-relative evidence source.
        path_parsed = urllib.parse.urlsplit(repo_path)
        if not (repo_path != value and not path_parsed.scheme):
            raise line_error(article, article.body_start_line,
                             f"unsupported evidence URL {source!r}")
    if value.startswith("//"):
        raise line_error(article, article.body_start_line,
                         f"unsupported evidence URL {source!r}")
    if value.startswith("/"):
        return context.resolve(value, article.category, article,
                               article.body_start_line).href
    if repo_path and (context.repo / repo_path).exists():
        return None

    # Keep the existing dangling-target wording for missing relative sources,
    # but do not let a relative value resolve as a site article by accident.
    try:
        path, _query, _fragment = context._normalise_path(repo_path, article.category)
    except BuildError as exc:
        raise line_error(article, article.body_start_line, str(exc)) from exc
    raise line_error(article, article.body_start_line,
                     f"dangling internal target {source!r} (resolved as {path})")


def markdown_rel(article: article_data.Article) -> str:
    return f"{article.category}/{article.slug}.md"


def markdown_path(article: article_data.Article) -> str:
    return "/" + markdown_rel(article)


def markdown_url(article: article_data.Article) -> str:
    return urlmap.SITE_ORIGIN + markdown_path(article)


def article_modified(article: article_data.Article, context: BuildContext) -> str:
    return article.updated or context.dates.last_modified(article.path)


def render_agent_prompt(article: article_data.Article) -> str:
    if not article.agent_prompt:
        return ""
    prompt = article.agent_prompt
    return ("  <div class=\"prompt-card\">\n"
            "    <span class=\"prompt-label\">PASTE THIS TO YOUR AI AGENT — IT DOES THE REST</span>\n"
            f"    <code>{esc_text(prompt)}</code>\n"
            f"    <button type=\"button\" class=\"prompt-copy\" data-copy=\"{esc_attr(prompt)}\">"
            "COPY THE PROMPT</button>\n"
            "  </div>")


def render_commands(article: article_data.Article) -> str:
    if not article.commands:
        return ""
    out: list[str] = []
    for item in article.commands:
        command = item["cmd"]
        note = item["note"]
        out.append("  <div class=\"prompt-card\">")
        out.append("    <span class=\"prompt-label\">RUN THIS XERJ COMMAND</span>")
        out.append(f"    <code>{esc_text(command)}</code>")
        out.append(f"    <button type=\"button\" class=\"prompt-copy\" data-copy=\"{esc_attr(command)}\">"
                   "COPY COMMAND</button>")
        out.append(f"    <span class=\"hero-proof\">{esc_text(note)}</span>")
        out.append("  </div>")
    return "\n".join(out)


def _split_tldr(body: str) -> tuple[str, str]:
    lines = body.splitlines()
    start = next((i for i, line in enumerate(lines) if line.strip()), 0)
    end = start
    while end < len(lines) and lines[end].strip():
        end += 1
    return "\n".join(lines[start:end]).strip(), "\n".join(lines[end:]).strip()


def _md_header_value(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def render_markdown_twin(article: article_data.Article, context: BuildContext) -> str:
    """Emit the agent-readable Markdown twin without HTML presentation chrome."""
    modified = article_modified(article, context)
    tldr, body = _split_tldr(article.body)
    source = article.path.relative_to(context.repo).as_posix()
    out = [
        f"{GENERATOR_PREFIX}{article.category}/{article.slug}.md instead -->",
        "---",
        f"title: {_md_header_value(article.title)}",
        f"canonical: {_md_header_value(urlmap.deployed_url(article.output_rel))}",
        f"updated: {_md_header_value(modified)}",
        f"source: {_md_header_value(source)}",
        "---",
        "",
        f"# {article.h1}",
        "",
        tldr,
    ]
    if article.agent_prompt:
        out += ["", "## Agent prompt", "", "```text", article.agent_prompt, "```"]
    if article.commands:
        out += ["", "## Commands", ""]
        for index, item in enumerate(article.commands, start=1):
            out += [f"### Command {index}", "", f"Note: {item['note']}", "",
                    "```sh", item["cmd"], "```", ""]
        while out and out[-1] == "":
            out.pop()
    if body:
        out += ["", body]

    out += ["", "## FAQ", ""]
    for item in article.faq:
        out += [f"### {item['q'].strip()}", "", item["a"].strip(), ""]
    if out[-1] == "":
        out.pop()

    # No evidence block means no provenance section at all.  An "## Evidence"
    # heading with a placeholder under it is worse than silence: it tells a
    # reader the article was sourced and then shows nothing.  Sources that ARE
    # present still go through _metadata_link and still have to resolve.
    if article.evidence:
        out += ["", "## Evidence", ""]
        for item in article.evidence:
            href = _metadata_link(item["source"], article, context)
            source = item["source"].strip()
            rendered_source = (f"[{source}]({href})" if href is not None
                               else f"`{source}`")
            out.append(f"- {item['claim'].strip()} — {rendered_source}")

    out += ["", "## Related", ""]
    if article.links_out:
        for raw in article.links_out:
            target = context.resolve_article_target(raw, article, article.body_start_line)
            out.append(f"- [{target.label}]({target.href})")
    else:
        out.append("No related pages are listed.")
    return "\n".join(out).rstrip() + "\n"


def render_article_sections(article: article_data.Article, context: BuildContext) -> str:
    body_blocks = render_markdown_blocks(article, context)
    out: list[str] = []
    if body_blocks:
        out.append(body_blocks[0])
    prompt = render_agent_prompt(article)
    if prompt:
        out.append(prompt)
    commands = render_commands(article)
    if commands:
        out.append(commands)
    out.extend(body_blocks[1:])
    out.append("  <h2>FAQ</h2>")
    for item in article.faq:
        # No grammar rule on the question string. A real user types "The
        # indexer died overnight." and matching that phrasing verbatim is the
        # whole mechanism this content depends on; a question-word validator
        # rejected exactly the strings worth matching. Structure (4-8 entries)
        # is still enforced in article_data.py.
        question = item["q"].strip()
        out.append(f"  <h3>{_inline(question, article, article.body_start_line, context.markdown_href)}</h3>")
        out.append("  <p>" + _inline(item["a"].strip(), article, article.body_start_line,
                                      context.markdown_href) + "</p>")

    # Same rule as the Markdown twin: the whole section is omitted when there
    # is no evidence block, so no page ships an empty "Evidence" heading.
    if article.evidence:
        out.append("  <h2>Evidence</h2>")
        out.append("  <ul>")
        for item in article.evidence:
            href = _metadata_link(item["source"], article, context)
            source = item["source"].strip()
            if href is None:
                source_html = f"<code>{esc_text(source)}</code>"
            else:
                source_html = f'<a href="{esc_attr(href)}">{esc_text(source)}</a>'
            out.append("    <li>" + _inline(item["claim"].strip(), article,
                                              article.body_start_line,
                                              context.markdown_href)
                       + " — " + source_html + "</li>")
        out.append("  </ul>")

    out.append("  <h2>Related</h2>")
    if article.links_out:
        out.append("  <ul>")
        for raw in article.links_out:
            target = context.resolve_article_target(raw, article, article.body_start_line)
            out.append(f'    <li><a href="{esc_attr(target.href)}">'
                       f"{esc_text(target.label)}</a></li>")
        out.append("  </ul>")
    else:
        out.append("  <p>No related pages are listed.</p>")
    return "\n".join(out)


