"""Synthetic labelled-email corpus for the discussion-1012 classification prototype.

This corpus is ORIGINAL TEXT generated by this script, not sourced from any
real mailbox or third-party dataset — written for this measurement so there
is no licence question and no privacy question. It is a sanity-check corpus,
not a claim about accuracy on real inboxes: template-generated text is more
separable than a real mailbox (real "personal" mail sometimes contains a
dollar figure, real newsletters sometimes ask a direct question). Treat the
numbers in README.md as "does the mechanism work at all", not as a production
accuracy estimate.

Four labels, chosen to match the ones discussion #1012 used as its example:
invoice, newsletter, personal, needs-reply. Deterministic (seed 7): rerunning
this script reproduces byte-identical corpus.json.

Usage: python3 gen_corpus.py  ->  writes corpus.json (train+test, labelled)
"""
import json
import random

random.seed(7)

FIRST_NAMES = ["Alex", "Priya", "Jonas", "Mei", "Sara", "Tomás", "Nina", "Ola",
               "Derek", "Fatima", "Luca", "Hana", "Owen", "Ingrid", "Kwame", "Yuki"]
COMPANIES = ["Northwind Supply", "Bluepeak Logistics", "Harborline Freight",
             "Cedarline Studio", "Voss & Rane", "Marlowe Analytics",
             "Fenwick Cloud", "Atlas Facilities", "Ridgeway Consulting",
             "Greenfield Robotics"]
PRODUCTS = ["the March hardware order", "consulting services (Q3)",
            "the annual support contract", "the office furniture delivery",
            "the API usage overage", "the catering for the offsite",
            "the printer maintenance plan", "the freight for pallet #4"]
TOPICS = ["what shipped this week", "our product roadmap",
          "three things we shipped", "a customer story worth reading",
          "what changed in the release", "upcoming maintenance windows",
          "our hiring plans", "a recap of the community call"]
PLANS = ["grab dinner Thursday", "catch the early train Saturday",
         "swing by before the game", "call you this weekend",
         "bring the kids over Sunday", "meet at the usual place at six",
         "drop off the keys tomorrow", "join for the hike next weekend"]
QUESTIONS = ["confirm the delivery window", "approve the attached budget",
             "pick a time for the walkthrough",
             "tell me which option you prefer",
             "sign off on the draft before Friday",
             "confirm your seat for the workshop",
             "let me know if the numbers look right",
             "decide between the two vendors"]


def rand_amount():
    return f"${random.randint(80, 48000):,}.{random.randint(0, 99):02d}"


def rand_date():
    month = random.choice(["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul",
                            "Aug", "Sep", "Oct", "Nov", "Dec"])
    return f"{month} {random.randint(1, 28)}"


def invoice(i):
    company = random.choice(COMPANIES)
    amount = rand_amount()
    due = rand_date()
    inv_no = f"INV-{10000 + i}"
    subject = f"Invoice {inv_no} from {company} — {amount} due {due}"
    body = (
        f"Please find attached invoice {inv_no} for {random.choice(PRODUCTS)}. "
        f"Amount due: {amount}, payable by {due}. Remit to the account on file "
        f"and reference {inv_no} on the transfer. A late fee of 1.5% applies "
        f"after the due date. Questions about this invoice can go to "
        f"billing@{company.lower().replace(' ', '').replace('&', '')}.example."
    )
    return subject, body


def newsletter(i):
    company = random.choice(COMPANIES)
    topic = random.choice(TOPICS)
    subject = f"This week at {company}: {topic}"
    body = (
        f"Hi there — here is this week's digest from {company}. This issue: "
        f"{topic}. We publish every Friday and read every reply, though this "
        f"address is not monitored for support. If this isn't useful anymore, "
        f"unsubscribe any time with the link at the bottom, no hard feelings."
    )
    return subject, body


def personal(i):
    name = random.choice(FIRST_NAMES)
    friend = random.choice(FIRST_NAMES)
    plan = random.choice(PLANS)
    subject = random.choice([f"hey {name}", "quick one", "this weekend?",
                              "long time!", f"re: {friend}'s thing"])
    body = (
        f"Hey {name}, it's been way too long. Was thinking we could "
        f"{plan} — no pressure either way, just wanted to catch up. "
        f"{friend} said you've been swamped. Say hi to everyone for me!"
    )
    return subject, body


def needs_reply(i):
    company = random.choice(COMPANIES)
    q = random.choice(QUESTIONS)
    subject = f"Need your input: {q}"
    body = (
        f"Hi — following up from {company}. Could you {q} by end of day "
        f"{rand_date()}? I don't want to move ahead without hearing from "
        f"you first. Let me know either way, even if the answer is 'not yet'."
    )
    return subject, body


GENERATORS = {
    "invoice": invoice,
    "newsletter": newsletter,
    "personal": personal,
    "needs-reply": needs_reply,
}

PER_LABEL_TRAIN = 50
PER_LABEL_TEST = 15

rows = []
for label, gen in GENERATORS.items():
    seen = set()
    n = 0
    i = 0
    while n < PER_LABEL_TRAIN + PER_LABEL_TEST:
        i += 1
        subject, body = gen(i)
        key = subject + body
        if key in seen:
            continue
        seen.add(key)
        rows.append({"label": label, "subject": subject, "text": body,
                     "split": "train" if n < PER_LABEL_TRAIN else "test"})
        n += 1

# Hand-authored, deliberately boundary-crossing. The templated generators
# above give each label near-exclusive vocabulary ("Invoice", "unsubscribe",
# "Hey <name>", "confirm by") which the vote can key on trivially — these
# instead borrow another label's words and topic on purpose (money in a
# personal note, a direct question in a newsletter, no "invoice" anywhere in
# an invoice) so a perfect score here would mean something.
HARD = [
    ("invoice", "did that ever go through?",
     "Hey Priya, quick check — did the transfer for last month's freight land "
     "yet? Should have been around forty-eight hundred, reference was on the "
     "packing slip. No rush, just reconciling the books this week."),
    ("personal", "owe you for gas",
     "Hey! Can you send me $40 whenever for the gas we split on the drive back? "
     "Venmo's fine, or just get me back next time you're over. No rush at all."),
    ("newsletter", "before Friday's launch",
     "Quick note from the team before Friday: we could use your take — reply "
     "and tell us which tagline you'd run with, A or B. We publish the results "
     "in next week's issue either way, so no wrong answer, just curious."),
    ("needs-reply", "This week at Cedarline: two quick things",
     "Hi — this week's rundown from the studio: the mockups are attached and "
     "we shipped the new brand kit. One thing before Friday though: I do need "
     "you to confirm the print run number, otherwise the press slot slips."),
    ("invoice", "for the offsite",
     "Hi team, wrapping up the offsite numbers. Catering came to $1,180, venue "
     "was $2,600. Same split as always — let accounting know if your card "
     "wasn't the one charged so we can true it up before month end."),
    ("personal", "hey, free this weekend?",
     "Hey Owen, free this weekend? Also — still owe you for the concert "
     "tickets, want to say $65? Let me know what works, either Venmo or cash "
     "when I see you."),
    ("newsletter", "Bluepeak Logistics: a customer story worth reading",
     "This issue: a customer story worth reading, plus what shipped this "
     "week. We publish every Friday. Reading time about four minutes. "
     "Unsubscribe any time with the link below, no hard feelings."),
    ("needs-reply", "one thing before I book this",
     "Before I book the freight slot I need a yes or no on the pallet count — "
     "24 or 32? Vendor holds the rate until 5pm today, after that it resets "
     "and we lose the discount, so whenever you get a sec."),
]
seen_hard = set()
for label, subject, body in HARD:
    key = subject + body
    assert key not in seen_hard, "duplicate hard example"
    seen_hard.add(key)
    rows.append({"label": label, "subject": subject, "text": body, "split": "hard"})

random.Random(11).shuffle(rows)
json.dump(rows, open("corpus.json", "w"), indent=1)
train = sum(r["split"] == "train" for r in rows)
test = sum(r["split"] == "test" for r in rows)
hard = sum(r["split"] == "hard" for r in rows)
print(f"corpus.json written: {len(rows)} emails ({train} train / {test} test / "
      f"{hard} hard), {len(GENERATORS)} labels")
